import { build } from 'esbuild'
import { createServer } from 'node:http'
import { chromium, expect } from '@playwright/test'
import assert from 'node:assert/strict'
const result = await build({ entryPoints: ['test/settings-page-fixture.tsx'], bundle: true, write: false, format: 'iife', jsx: 'automatic', loader: { '.css': 'text' } })
const server = createServer((req, res) => {
  res.setHeader('Content-Type', req.url === '/app.js' ? 'text/javascript' : 'text/html; charset=utf-8')
  res.end(req.url === '/app.js' ? result.outputFiles[0].text : '<!doctype html><style>body{margin:0}#host{position:fixed;inset:50px 20px 20px;overflow:auto;padding:18px 12px 32px;border:1px solid #ddd;box-sizing:border-box}#root{width:100%;padding-bottom:16px}</style><div id="host"><div id="root"></div></div><script src="/app.js"></script>')
})
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
const browser = await chromium.launch({ channel: 'msedge', headless: true })
try {
  for (const width of [390, 1000]) {
    const page = await browser.newPage({ viewport: { width, height: 750 } })
    await page.goto(`http://127.0.0.1:${server.address().port}`)
    await page.waitForFunction(() => !!window.harness.releaseList)
    await expect(page.locator('.dmm-navigation')).toHaveCount(0)
    await expect(page.getByText('更多模型操作')).toHaveCount(0)
    await page.evaluate(() => window.harness.releaseList())
    const choose = async (name, value) => {
      await page.getByRole('button', { name, exact: true }).click()
      const list = page.getByRole('listbox', { name, exact: true })
      await list.selectOption(value); await list.press('Enter')
    }
    await choose('已添加供应商', 'test')
    await choose('已配置模型', JSON.stringify(['test', 'a']))
    await expect(page.getByLabel('模型 ID', { exact: true })).toHaveValue('a')
    const save = page.getByRole('button', { name: '保存', exact: true })
    await expect(save).toHaveCount(1)
    await expect(save).toHaveAttribute('title', '保存到配置文件')
    await expect(save).toBeDisabled()
    const savePosition = await save.boundingBox()
    const reasoning = page.getByRole('checkbox', { name: '推理 / 思考', exact: true })
    await reasoning.check()
    await expect(save).toBeEnabled()
    await expect(page.locator('.dmm-save-bar')).toContainText('有未保存的更改')
    await expect(reasoning).toBeChecked()
    await page.getByText('高级设置', { exact: false }).first().click()
    await expect(page.getByLabel('medium 请求值')).toHaveValue('medium')
    await page.getByLabel('medium 请求值').fill('enabled')
    await reasoning.uncheck()
    await expect(page.getByLabel('推理档配置')).toHaveValue('disabled')
    await reasoning.check()
    await expect(page.getByLabel('medium 请求值')).toHaveValue('enabled')
    await page.getByText('高级设置', { exact: false }).first().click()
    const nav = await page.locator('.dmm-navigation').boundingBox()
    await page.getByRole('button', { name: '编辑价格', exact: true }).click()
    await page.locator('.dmm-editor-scroll').evaluate(el => { el.scrollTop = el.scrollHeight })
    await choose('已配置模型', JSON.stringify(['test', 'b']))
    await page.waitForFunction(() => !!window.harness.release)
    const assertLayout = async () => {
      const metrics = await page.evaluate(() => {
        const host = document.querySelector('#host'), editor = document.querySelector('.dmm-editor-scroll')
        return { hostTop: host.scrollTop, hostHeight: host.clientHeight, hostScroll: host.scrollHeight, pageTop: window.scrollY, editorHeight: editor.clientHeight }
      })
      assert.equal(metrics.hostTop, 0)
      assert.equal(metrics.pageTop, 0)
      assert.ok(metrics.hostScroll <= metrics.hostHeight + 1, JSON.stringify(metrics))
      assert.ok(metrics.editorHeight > 100)
      assert.equal((await page.locator('.dmm-navigation').boundingBox()).y, nav.y)
      const footer = await save.boundingBox()
      assert.equal(footer.y, savePosition.y)
      assert.ok(footer.y + footer.height <= 750)
      const editor = await page.locator('.dmm-editor-scroll').boundingBox()
      assert.ok(editor.y + editor.height <= footer.y)
    }
    await assertLayout()
    await expect(page.locator('button.dmm-primary')).toBeDisabled()
    await page.evaluate(() => window.harness.release())
    await expect(page.getByLabel('模型 ID', { exact: true })).toHaveValue('b')
    await expect(page.getByRole('button', { name: '保存', exact: true })).toBeDisabled()
    await assertLayout()
    const currencyBox = await page.getByLabel('计价币种').boundingBox()
    const sourceBox = await page.getByLabel('价格数据源').boundingBox()
    assert.ok(Math.abs(currencyBox.y - sourceBox.y) < 1)
    const inputBox = await page.getByLabel('输入', { exact: true }).boundingBox()
    const outputBox = await page.getByLabel('输出', { exact: true }).boundingBox()
    assert.ok(Math.abs(inputBox.y - outputBox.y) < 1)
    await page.screenshot({ path: `work/pricing-compact-${width}.png` })
    await page.getByRole('button', { name: '编辑价格', exact: true }).click()
    await assertLayout()
    await page.screenshot({ path: `work/settings-page-${width}.png` })
    await page.close()
  }
  console.log('Dedicated settings page passed: isolated scrolling, fixed navigation, delayed model switch and price collapse.')
} finally { await browser.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)) }
